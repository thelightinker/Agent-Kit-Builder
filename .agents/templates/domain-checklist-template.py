import sys
import os
import re
import json
import subprocess
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

class VerificationEngine:
    def __init__(self, kit_root="."):
        self.root = Path(kit_root)
        self.results = []

    def log_result(self, priority, name, passed, details=""):
        status = "[PASS]" if passed else "[FAIL]"
        self.results.append({
            "priority": priority,
            "name": name,
            "passed": passed,
            "details": details
        })
        print(f"  {status} {priority}: {name}")
        if details and not passed:
            print(f"         └─ Error: {details}")

    # Archetype 1: Structural & Presence Check
    def check_presence(self, required_files):
        print("\n🔍 Checking Structural & Presence Requirements...")
        for rfile in required_files:
            fpath = self.root / rfile
            exists = fpath.exists() and fpath.stat().st_size > 0
            self.log_result("P0", f"File presence: {rfile}", exists, "File missing or empty" if not exists else "")

    # Archetype 2: Negative Completeness Matrix (Omission Detection)
    def check_negative_completeness(self, target_file, required_items):
        print(f"\n📋 Checking Negative Completeness Matrix on {target_file}...")
        fpath = self.root / target_file
        if not fpath.exists():
            self.log_result("P1", f"Negative completeness: {target_file}", False, "Target file does not exist")
            return

        content = fpath.read_text("utf-8", errors="replace").lower()
        for item in required_items:
            found = item.lower() in content
            self.log_result("P1", f"Required item: '{item}'", found, f"Mandatory requirement '{item}' is MISSING (Omission error)")

    # Archetype 3: Deterministic Computation Verification
    def check_deterministic_computation(self, script_path):
        print(f"\n🔢 Checking Deterministic Arithmetic Integrity ({script_path})...")
        fpath = self.root / script_path
        if not fpath.exists():
            self.log_result("P2", f"Calc script: {script_path}", False, "Calculation script missing")
            return
        
        try:
            res = subprocess.run([sys.executable, str(fpath)], capture_output=True, text=True, timeout=10)
            passed = res.returncode == 0
            self.log_result("P2", f"Arithmetic script execution", passed, res.stderr.strip() if not passed else "")
        except Exception as e:
            self.log_result("P2", f"Arithmetic script execution", False, str(e))

    # Archetype 5: System Command / Test Runner

    def check_system_command(self, priority, name, cmd_args):
        print(f"\n⚙️ Running System Verification: {name}...")
        try:
            res = subprocess.run(cmd_args, capture_output=True, text=True, timeout=30)
            passed = res.returncode == 0
            self.log_result(priority, name, passed, res.stderr.strip() if not passed else "")
        except Exception as e:
            self.log_result(priority, name, False, str(e))

    def summarize(self):
        total = len(self.results)
        passed = sum(1 for r in self.results if r["passed"])
        failed = total - passed
        print("\n" + "=" * 60)
        print(f"VERIFICATION SUMMARY: {passed}/{total} checks passed ({failed} failed)")
        print("=" * 60)
        return failed == 0

def main():
    engine = VerificationEngine()
    
    # 1. P0: Structural
    engine.check_presence(["manifest.json"])
    
    # 2. P1: Negative Completeness
    # engine.check_negative_completeness("deliverable.md", ["summary", "evidence", "next steps"])
    
    # 3. Summary
    success = engine.summarize()
    sys.exit(0 if success else 1)

if __name__ == "__main__":
    main()
